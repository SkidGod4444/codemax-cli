/** Logo lines for a terminal this wide: the full 76-column logo from 78 columns, none below. */
export function logoLines(width: number): string[] {
  // Squeezed to half width the letters run together, so narrow terminals get the text title instead.
  if (width < 78) return [];
  const on = (r: number, c: number) => Number(GRID[r]?.[c] ?? "0") >= 4;
  const lines: string[] = [];
  for (let r = 0; r < GRID.length; r += 2) {
    let line = "";
    for (let c = 0; c < GRID[0]!.length; c++) {
      const up = on(r, c), down = on(r + 1, c);
      line += up && down ? "█" : up ? "▀" : down ? "▄" : " ";
    }
    lines.push(line.replace(/\s+$/, ""));
  }
  return lines;
}
